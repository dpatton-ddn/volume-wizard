// Codes used: name_taken, insufficient_capacity, invalid_tier, invalid_request, unavailable, not_found
export class ApiError extends Error {
  status: number;
  code: string;
  constructor(status: number, code: string, message: string) {
    super(message);
    this.name = 'ApiError';
    this.status = status;
    this.code = code;
  }
}
